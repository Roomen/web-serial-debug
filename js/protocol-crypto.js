window.skCrc16 = function (bytes) {
	let wResult = 0xFFFF
	let wTableNo = 0
	const len = bytes.length
	for (let i = 0; i < len; i++) {
		wTableNo = ((wResult >> 8) ^ bytes[i]) & 0xff
		wResult = ((wResult << 8) ^ window.skCrc16Table[wTableNo]) & 0xffff
	}
	return wResult & 0xffff
}

