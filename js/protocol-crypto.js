window.skAes128EcbEncrypt = function (plainBytes, keyBytes) {
	const rk = window.skAesKeyExpansion(new Uint8Array(keyBytes.subarray(0, 16)))
	const plain = new Uint8Array(plainBytes)
	const blocks = Math.floor(plain.length / 16) + 1
	const out = new Uint8Array(blocks * 16)
	out.fill(0)
	out.set(plain)
	for (let b = 0; b < blocks; b++) {
		const enc = window.skAes128EcbEncryptBlock(out.subarray(b * 16, b * 16 + 16), rk)
		out.set(enc, b * 16)
	}
	return out
}

