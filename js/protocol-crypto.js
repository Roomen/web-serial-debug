window.skAesKeyExpansion = function (key) {
	const rk = new Uint8Array(176)
	rk.set(key.subarray(0, 16))
	let i = 16
	for (let round = 1; round <= 10; round++) {
		let t0 = rk[i - 4]
		let t1 = rk[i - 3]
		let t2 = rk[i - 2]
		let t3 = rk[i - 1]
		const tt = t0
		t0 = t1; t1 = t2; t2 = t3; t3 = tt
		t0 = window.skAesSbox[t0]
		t1 = window.skAesSbox[t1]
		t2 = window.skAesSbox[t2]
		t3 = window.skAesSbox[t3]
		t0 ^= window.skAesRcon[round - 1]
		rk[i] = rk[i - 16] ^ t0
		rk[i + 1] = rk[i - 15] ^ t1
		rk[i + 2] = rk[i - 14] ^ t2
		rk[i + 3] = rk[i - 13] ^ t3
		for (let k = 4; k < 16; k += 4) {
			rk[i + k] = rk[i + k - 4] ^ rk[i + k - 16]
			rk[i + k + 1] = rk[i + k - 3] ^ rk[i + k - 15]
			rk[i + k + 2] = rk[i + k - 2] ^ rk[i + k - 14]
			rk[i + k + 3] = rk[i + k - 1] ^ rk[i + k - 13]
		}
		i += 16
	}
	return rk
}

window.skAesXtime = function (x) {
	return ((x << 1) ^ ((x & 0x80) ? 0x1b : 0)) & 0xff
}

window.skAesGmul = function (a, b) {
	let p = 0
	for (let i = 0; i < 8; i++) {
		if (b & 1) p ^= a
		const hi = a & 0x80
		a = (a << 1) & 0xff
		if (hi) a ^= 0x1b
		b >>= 1
	}
	return p & 0xff
}

window.skAesAddRoundKey = function (s, rk, offset) {
	for (let i = 0; i < 16; i++) s[i] ^= rk[offset + i]
}

window.skAesSubBytes = function (s, box) {
	for (let i = 0; i < 16; i++) s[i] = box[s[i]]
}

window.skAesShiftRows = function (s) {
	const t = new Uint8Array(16)
	for (let r = 0; r < 4; r++) {
		for (let c = 0; c < 4; c++) {
			t[r + 4 * c] = s[r + 4 * ((c + r) % 4)]
		}
	}
	s.set(t)
}

window.skAesInvShiftRows = function (s) {
	const t = new Uint8Array(16)
	for (let r = 0; r < 4; r++) {
		for (let c = 0; c < 4; c++) {
			t[r + 4 * c] = s[r + 4 * ((c - r + 4) % 4)]
		}
	}
	s.set(t)
}

window.skAesMixColumns = function (s) {
	for (let c = 0; c < 4; c++) {
		const o = 4 * c
		const a0 = s[o], a1 = s[o + 1], a2 = s[o + 2], a3 = s[o + 3]
		s[o] = window.skAesGmul(a0, 2) ^ window.skAesGmul(a1, 3) ^ a2 ^ a3
		s[o + 1] = a0 ^ window.skAesGmul(a1, 2) ^ window.skAesGmul(a2, 3) ^ a3
		s[o + 2] = a0 ^ a1 ^ window.skAesGmul(a2, 2) ^ window.skAesGmul(a3, 3)
		s[o + 3] = window.skAesGmul(a0, 3) ^ a1 ^ a2 ^ window.skAesGmul(a3, 2)
	}
}

